// findKb — первая статья, ключевое слово которой есть в тексте (текст уже в нижнем регистре).
func findKb(t string) *KbArticle {
	for i := range KB {
		for _, k := range KB[i].Keywords {
			if strings.Contains(t, k) {
				return &KB[i]
			}
		}
	}
	return nil
}

func kbByID(id string) *KbArticle {
	for i := range KB {
		if KB[i].ID == id {
			return &KB[i]
		}
	}
	panic("нет статьи " + id)
}
